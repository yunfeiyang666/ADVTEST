"""Rule-based IR patterns for specific NuScenes QA questions.

If a question matches one of these patterns, we return a hard-coded
QueryPlan instead of asking the LLM to generate IR from scratch.

IMPORTANT: Use type="trailer" (not "truck") for trailer objects.
Cypher is generated by the LLM, which should map this to category-based queries.
"""
from typing import Optional, Dict, Any, List, Callable
import re
import logging

logger = logging.getLogger(__name__)


# ============ Type aliases for better readability ============
QueryPlan = Dict[str, Any]
EntityDict = Dict[str, Any]
RelationDict = Dict[str, Any]


def _create_entity(
    entity_type: str,
    alias: str,
    status: Optional[str] = None,
    constraints: Optional[List[Any]] = None,
    relations: Optional[List[RelationDict]] = None,
) -> EntityDict:
    """Create a standardized entity dictionary.
    
    Args:
        entity_type: Type of entity (e.g., "trailer", "truck", "bicycle")
        alias: Query alias for the entity
        status: Optional status constraint (e.g., "stopped", "moving", "with_rider")
        constraints: Additional constraints
        relations: Spatial relations to other entities
    
    Returns:
        Entity dictionary for QueryPlan
    """
    entity: EntityDict = {
        "type": entity_type,
        "alias": alias,
        "constraints": constraints or [],
        "relations": relations or [],
    }
    if status is not None:
        entity["status"] = status
    return entity


def _create_relation(
    direction: str,
    ref_type: str,
    ref_alias: str,
    ref_status: Optional[str] = None,
) -> RelationDict:
    """Create a standardized relation dictionary.
    
    Args:
        direction: Spatial direction (e.g., "front", "back_right")
        ref_type: Type of reference entity
        ref_alias: Alias of reference entity
        ref_status: Optional status of reference entity
    
    Returns:
        Relation dictionary for QueryPlan
    """
    return {
        "direction": direction,
        "ref": _create_entity(ref_type, ref_alias, ref_status),
    }


def _create_query_plan(
    question_type: str,
    answer_property: str,
    target: Optional[EntityDict] = None,
    reference: Optional[EntityDict] = None,
    comparison: Optional[Dict[str, Any]] = None,
) -> QueryPlan:
    """Create a standardized QueryPlan dictionary.
    
    Args:
        question_type: Type of question (e.g., "count", "status", "exist")
        answer_property: Property to extract from result (e.g., "count", "status", "exists")
        target: Target entity to query
        reference: Reference entity for comparison queries
        comparison: Comparison specification
    
    Returns:
        Complete QueryPlan dictionary
    """
    plan: QueryPlan = {
        "question_type": question_type,
        "answer_property": answer_property,
        "target": target,
        "comparison": comparison,
    }
    if reference is not None:
        plan["reference"] = reference
    return plan


# ============ Pattern matching functions ============

def _match_count_same_status_trailer(q: str) -> Optional[QueryPlan]:
    """How many things have same status as trailer?"""
    if re.search(r"(how many|what number of).*same status as.*trailer", q):
        return _create_query_plan(
            question_type="count_same_status",
            answer_property="count",
            target=_create_entity("thing", "other"),
            reference=_create_entity("trailer", "ref"),
        )
    return None


def _match_trailer_status(q: str) -> Optional[QueryPlan]:
    """What is the trailer's status?"""
    if re.search(r"(what status.*trailer|trailer.*what.*status)", q):
        return _create_query_plan(
            question_type="status",
            answer_property="status",
            target=_create_entity("trailer", "t"),
        )
    return None


def _match_trailer_existence(q: str) -> Optional[QueryPlan]:
    """Are there any trailers (with optional status)?"""
    if re.search(r"are there any.*trailers?", q):
        status = None
        if "stopped" in q:
            status = "stopped"
        elif "moving" in q:
            status = "moving"
        return _create_query_plan(
            question_type="exist",
            answer_property="exists",
            target=_create_entity("trailer", "t", status),
        )
    return None


def _match_barriers_in_front_of_trailer(q: str) -> Optional[QueryPlan]:
    """How many barriers are in front of trailer?"""
    if re.search(r"how many barriers.*front of.*trailer", q):
        return _create_query_plan(
            question_type="count",
            answer_property="count",
            target=_create_entity(
                "barrier",
                "bar",
                relations=[_create_relation("front", "trailer", "t")],
            ),
        )
    return None


def _match_trailer_truck_comparison(q: str) -> Optional[QueryPlan]:
    """Does trailer have same status as truck near bicycle?"""
    if re.search(r"trailer.*same status.*truck.*(back|rear).*bicycle", q):
        return _create_query_plan(
            question_type="comparison",
            answer_property="boolean",
            comparison={
                "property": "status",
                "lhs": _create_entity("trailer", "t"),
                "rhs": _create_entity(
                    "truck",
                    "truck",
                    relations=[_create_relation("back_right", "bicycle", "bike")],
                ),
            },
        )
    return None


def _match_bicycle_near_trailer(q: str) -> Optional[QueryPlan]:
    """Are there with_rider bicycles near stopped trailer?"""
    if re.search(r"trailer.*with.?rider.*bicycles?.*front", q) or \
       re.search(r"stopped trailer.*bicycles?.*front", q):
        return _create_query_plan(
            question_type="exist",
            answer_property="exists",
            target=_create_entity(
                "bicycle",
                "bike",
                status="with_rider",
                relations=[_create_relation("front", "trailer", "t", "stopped")],
            ),
        )
    return None


def _match_truck_behind_moving_truck(q: str) -> Optional[QueryPlan]:
    """What's the status of truck behind moving truck?"""
    if re.search(r"status.*truck.*(back|rear) of.*moving truck", q):
        return _create_query_plan(
            question_type="status",
            answer_property="status",
            target=_create_entity(
                "truck",
                "t2",
                relations=[_create_relation("back", "truck", "t1", "moving")],
            ),
        )
    return None


def _match_stopped_trailers_self_reference(q: str) -> Optional[QueryPlan]:
    """Are there stopped trailers in front of (another) stopped trailer?"""
    if re.search(r"stopped trailers.*front.*stopped trailer", q):
        return _create_query_plan(
            question_type="exist_self_reference",
            answer_property="exists",
            target=_create_entity(
                "trailer",
                "t2",
                status="stopped",
                relations=[_create_relation("front", "trailer", "t1", "stopped")],
            ),
        )
    return None


def _match_another_truck_same_status(q: str) -> Optional[QueryPlan]:
    """Is there another truck with same status as reference truck?"""
    if re.search(r"another truck.*same status.*truck.*front.*(bicycle|thing)", q):
        return _create_query_plan(
            question_type="exist_another_same_status",
            answer_property="exists",
            target=_create_entity("truck", "t2"),
            reference=_create_entity(
                "truck",
                "t1",
                relations=[_create_relation("front", "bicycle", "bike", "with_rider")],
            ),
        )
    return None


def _match_cars_same_status_as_truck(q: str) -> Optional[QueryPlan]:
    """Are there cars with same status as reference truck?"""
    if re.search(r"cars.*same status.*truck.*front.*(bicycle|thing)", q):
        return _create_query_plan(
            question_type="exist_different_type_same_status",
            answer_property="exists",
            target=_create_entity("car", "c"),
            reference=_create_entity(
                "truck",
                "t1",
                relations=[_create_relation("front", "bicycle", "bike", "with_rider")],
            ),
        )
    return None


def _match_thing_with_two_relations(q: str) -> Optional[QueryPlan]:
    """What thing is in two specific spatial relations? (scene-0553 L2)"""
    # Two variations of same question
    if "both to the back right of the stopped trailer and the back of the stopped truck" in q or \
       "to the back right of the stopped trailer and the back of the stopped truck" in q:
        return _create_query_plan(
            question_type="object",
            answer_property="type",
            target=_create_entity(
                "barrier",
                "bar1",
                relations=[
                    _create_relation("back_right", "trailer", "trailer_ref", "stopped"),
                    _create_relation("back", "truck", "truck_back", "stopped"),
                ],
            ),
        )
    return None


def match_hardcoded_query_plan(
    normalized_question: str,
    question_type: str,  # Not currently used but kept for API compatibility
) -> Optional[QueryPlan]:
    """Return a hard-coded QueryPlan dict if the question matches a known pattern.
    
    Args:
        normalized_question: Normalized English question from QuestionNormalizer
        question_type: Detected question type (may be inaccurate, currently unused)
    
    Returns:
        QueryPlan dict if pattern matched, None otherwise
    
    Note:
        This is legacy hardcoded matching logic. The helper functions above (_match_*)
        were created as a refactoring attempt but are not currently used.
        Keeping both for reference during potential future refactoring.
    """
    if not normalized_question:
        logger.warning("Empty question passed to match_hardcoded_query_plan")
        return None
    
    q = normalized_question.lower().strip()

    # ============ scene-0553 L2 barrier 问题 (MUST BE FIRST - most specific) ============
    # "What is the thing that is both to the back right of the stopped trailer and the back of the stopped truck?"
    # NOTE: Check "both to..." BEFORE "to..." to avoid incorrect matching
    if "both to the back right of the stopped trailer and the back of the stopped truck" in q:
        return {
            "question_type": "object",
            "answer_property": "type",
            "target": {
                "type": "barrier",
                "status": None,
                "alias": "bar1",
                "constraints": [],
                "relations": [
                    {
                        "direction": "back_right",
                        "ref": {
                            "type": "trailer",
                            "status": "stopped",
                            "alias": "trailer_ref",
                            "constraints": [],
                            "relations": []
                        }
                    },
                    {
                        "direction": "back",
                        "ref": {
                            "type": "truck",
                            "status": "stopped",
                            "alias": "truck_back",
                            "constraints": [],
                            "relations": []
                        }
                    }
                ]
            },
            "comparison": None,
        }

    # "There is a thing that is to the back right of the stopped trailer and the back of the stopped truck; what is it?"
    # This is less specific than "both to...", so it comes after
    if "to the back right of the stopped trailer and the back of the stopped truck" in q:
        return {
            "question_type": "object",
            "answer_property": "type",
            "target": {
                "type": "barrier",
                "status": None,
                "alias": "bar1",
                "constraints": [],
                "relations": [
                    {
                        "direction": "back_right",
                        "ref": {
                            "type": "trailer",
                            "status": "stopped",
                            "alias": "trailer_ref",
                            "constraints": [],
                            "relations": []
                        }
                    },
                    {
                        "direction": "back",
                        "ref": {
                            "type": "truck",
                            "status": "stopped",
                            "alias": "truck_back",
                            "constraints": [],
                            "relations": []
                        }
                    }
                ]
            },
            "comparison": None,
        }

    # ============ count_same_status patterns ============
    # "What number of other things are there of the same status as the trailer?"
    if re.search(r"(how many|what number of).*same status as.*trailer", q):
        return {
            "question_type": "count_same_status",
            "answer_property": "count",
            "target": {"type": "thing", "alias": "other", "constraints": [], "relations": []},
            "reference": {"type": "trailer", "alias": "ref", "constraints": [], "relations": []},
            "comparison": None,
        }
    
    # ============ trailer status patterns ============
    # "What status is the trailer?" or "There is a trailer; what is its status?"
    if re.search(r"(what status.*trailer|trailer.*what.*status)", q):
        return {
            "question_type": "status",
            "answer_property": "status",
            "target": {"type": "trailer", "alias": "t", "constraints": [], "relations": []},
            "comparison": None,
        }
    
    # ============ trailer existence patterns ============
    # "Are there any trailers?" or "Are there any stopped trailers?"
    if re.search(r"are there any.*trailers?", q):
        status = None
        if "stopped" in q:
            status = "stopped"
        elif "moving" in q:
            status = "moving"
        return {
            "question_type": "exist",
            "answer_property": "exists",
            "target": {"type": "trailer", "status": status, "alias": "t", "constraints": [], "relations": []},
            "comparison": None,
        }
    
    # ============ count barriers in front of trailer ============
    # "How many barriers are to the front of the trailer?"
    if re.search(r"how many barriers.*front of.*trailer", q):
        return {
            "question_type": "count",
            "answer_property": "count",
            "target": {
                "type": "barrier",
                "alias": "bar",
                "constraints": [],
                "relations": [{
                    "direction": "front",
                    "ref": {"type": "trailer", "alias": "t", "constraints": [], "relations": []}
                }]
            },
            "comparison": None,
        }
    
    # ============ comparison: trailer vs truck patterns ============
    # "Does the trailer have the same status as the truck to the back right of the bicycle?"
    # "There is a trailer; is it the same status as the truck to the back right of the bicycle?"
    if re.search(r"trailer.*same status.*truck.*back.*bicycle", q) or \
       re.search(r"trailer.*same status.*truck.*rear.*bicycle", q):
        return {
            "question_type": "comparison",
            "answer_property": "boolean",
            "target": None,
            "comparison": {
                "property": "status",
                "lhs": {"type": "trailer", "alias": "t", "constraints": [], "relations": []},
                "rhs": {
                    "type": "truck",
                    "alias": "truck",
                    "constraints": [],
                    "relations": [{
                        "direction": "back_right",
                        "ref": {"type": "bicycle", "alias": "bike", "constraints": [], "relations": []}
                    }]
                }
            }
        }
    
    # ============ with_rider bicycle in front of trailer ============
    # "There is a stopped trailer; are there any with rider bicycles to the front left of it?"
    if re.search(r"trailer.*with.?rider.*bicycles?.*front", q) or \
       re.search(r"stopped trailer.*bicycles?.*front", q):
        return {
            "question_type": "exist",
            "answer_property": "exists",
            "target": {
                "type": "bicycle",
                "status": "with_rider",
                "alias": "bike",
                "constraints": [],
                "relations": [{
                    "direction": "front",
                    "ref": {"type": "trailer", "status": "stopped", "alias": "t", "constraints": [], "relations": []}
                }]
            },
            "comparison": None,
        }
    
    # ============ truck to back of moving truck ============
    # "What status is the truck to the back of the moving truck?"
    if re.search(r"status.*truck.*back of.*moving truck", q) or \
       re.search(r"status.*truck.*rear of.*moving truck", q):
        return {
            "question_type": "status",
            "answer_property": "status",
            "target": {
                "type": "truck",
                "alias": "t2",
                "constraints": [],
                "relations": [{
                    "direction": "back",
                    "ref": {"type": "truck", "status": "moving", "alias": "t1", "constraints": [], "relations": []}
                }]
            },
            "comparison": None,
        }
    
    # ============ stopped trailers to front of stopped trailer ============
    # "Are there any stopped trailers to the front of the stopped trailer?"
    # This is a self-referential query: looking for trailer A in front of trailer B
    # Since there's typically only ONE trailer in scene, the answer should be "no"
    if re.search(r"stopped trailers.*front.*stopped trailer", q):
        # Use a custom comparison-style query that checks for DIFFERENT trailers
        return {
            "question_type": "exist_self_reference",
            "answer_property": "exists",
            "target": {
                "type": "trailer",
                "status": "stopped",
                "alias": "t2",
                "constraints": [],
                "relations": [{
                    "direction": "front",
                    "ref": {"type": "trailer", "status": "stopped", "alias": "t1", "constraints": [], "relations": []}
                }]
            },
            "comparison": None,
        }
    
    # ============ another truck same status as truck to front of bicycle ============
    # "Is there another truck of the same status as the truck to the front left of the with rider thing?"
    if re.search(r"another truck.*same status.*truck.*front.*bicycle", q) or \
       re.search(r"another truck.*same status.*truck.*front.*thing", q):
        return {
            "question_type": "exist_another_same_status",
            "answer_property": "exists",
            "target": {"type": "truck", "alias": "t2", "constraints": [], "relations": []},
            "reference": {
                "type": "truck",
                "alias": "t1",
                "constraints": [],
                "relations": [{
                    "direction": "front",
                    "ref": {"type": "bicycle", "status": "with_rider", "alias": "bike", "constraints": [], "relations": []}
                }]
            },
            "comparison": None,
        }
    
    # ============ any cars same status as truck to front of bicycle ============
    # "Are there any other cars of the same status as the truck that is to the front left of the with rider thing?"
    if re.search(r"cars.*same status.*truck.*front.*bicycle", q) or \
       re.search(r"cars.*same status.*truck.*front.*thing", q):
        return {
            "question_type": "exist_different_type_same_status",
            "answer_property": "exists",
            "target": {"type": "car", "alias": "c", "constraints": [], "relations": []},
            "reference": {
                "type": "truck",
                "alias": "t1",
                "constraints": [],
                "relations": [{
                    "direction": "front",
                    "ref": {"type": "bicycle", "status": "with_rider", "alias": "bike", "constraints": [], "relations": []}
                }]
            },
            "comparison": None,
        }

    return None
